  def question_type_badge_class(question)
    case question.response_type
    when 'scale'
      'badge-primary'
    when 'multi_choice'
      'badge-secondary'
    when 'text'
      'badge-accent'
    else
      'badge-ghost'
    end
  end

  def question_type_color(question)
    case question.response_type
    when 'scale'
      'text-primary'
    when 'multi_choice'
      'text-secondary'
    when 'text'
      'text-accent'
    else
      'text-base-content'
    end
  end
end
